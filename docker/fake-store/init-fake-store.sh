  --set=database_name="$POSTGRES_DB" \
  --set=readonly_user="$readonly_user" \
  --set=readonly_password="$readonly_password" \
  --set=store_timezone="$store_timezone" \
  --set=store_currency="$store_currency" <<'SQL'
