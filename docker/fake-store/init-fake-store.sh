set -eu

readonly_user="${FAKE_STORE_READONLY_USER:-sou2ai_store_reader}"
readonly_password="${FAKE_STORE_READONLY_PASSWORD:-sou2ai_store_reader_local}"
store_timezone="${FAKE_STORE_TIMEZONE:-Asia/Beirut}"
