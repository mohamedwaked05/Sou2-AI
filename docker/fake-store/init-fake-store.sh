    'CREATE ROLE %I LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L',
    :'readonly_user', :'readonly_password'
)
WHERE NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = :'readonly_user')\gexec
SELECT format(
    'ALTER ROLE %I LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L',
    :'readonly_user', :'readonly_password'
)\gexec
SELECT format('ALTER ROLE %I IN DATABASE %I SET default_transaction_read_only = on',
              :'readonly_user', :'database_name')\gexec
SELECT format('ALTER ROLE %I IN DATABASE %I SET statement_timeout = %L',
              :'readonly_user', :'database_name', '2000ms')\gexec

SELECT format('REVOKE ALL ON DATABASE %I FROM PUBLIC', :'database_name')\gexec
SELECT format('GRANT CONNECT ON DATABASE %I TO %I',
              :'database_name', :'readonly_user')\gexec
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE SCHEMA IF NOT EXISTS minimarket AUTHORIZATION CURRENT_USER;
CREATE SCHEMA IF NOT EXISTS private_internal AUTHORIZATION CURRENT_USER;
REVOKE ALL ON SCHEMA minimarket, private_internal FROM PUBLIC;

CREATE TABLE IF NOT EXISTS minimarket.store_configuration (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    business_timezone text NOT NULL,
    currency_code varchar(3) NOT NULL CHECK (currency_code ~ '^[A-Z]{3}$'),
    data_updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS minimarket.categories (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS minimarket.catalog_items (
    item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code text NOT NULL UNIQUE,
    merchant_sku text UNIQUE,
    ean_barcode text UNIQUE,
    display_label text NOT NULL,
    category_id integer REFERENCES minimarket.categories(category_id),
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS minimarket.stock_locations (
    location_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_code text NOT NULL UNIQUE,
    location_label text NOT NULL,
    location_type text NOT NULL CHECK (location_type IN ('BRANCH', 'WAREHOUSE'))
);

CREATE TABLE IF NOT EXISTS minimarket.stock_levels (
    location_id integer NOT NULL REFERENCES minimarket.stock_locations(location_id),
    item_id integer NOT NULL REFERENCES minimarket.catalog_items(item_id),
    physical_quantity numeric(12, 3) NOT NULL CHECK (physical_quantity >= 0),
    reorder_threshold numeric(12, 3) NOT NULL CHECK (reorder_threshold >= 0),
    desired_quantity numeric(12, 3) NOT NULL CHECK (
        desired_quantity >= reorder_threshold
    ),
    changed_at timestamptz NOT NULL,
    PRIMARY KEY (location_id, item_id)
);

CREATE TABLE IF NOT EXISTS minimarket.stock_reservations (
    reservation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id integer NOT NULL,
    item_id integer NOT NULL,
    held_quantity numeric(12, 3) NOT NULL CHECK (held_quantity > 0),
    reservation_state text NOT NULL CHECK (
        reservation_state IN ('ACTIVE', 'RELEASED', 'FULFILLED', 'CANCELLED')
    ),
    expires_at timestamptz,
    created_at timestamptz NOT NULL,
    FOREIGN KEY (location_id, item_id)
        REFERENCES minimarket.stock_levels(location_id, item_id)
);

CREATE TABLE IF NOT EXISTS minimarket.receipts (
    receipt_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number text NOT NULL UNIQUE,
    branch_location_id integer NOT NULL REFERENCES minimarket.stock_locations(location_id),
    receipt_state text NOT NULL CHECK (
        receipt_state IN ('COMPLETED', 'PENDING', 'CANCELLED', 'RETURNED')
    ),
    currency_code varchar(3) NOT NULL,
    completed_at timestamptz,
    created_at timestamptz NOT NULL,
    changed_at timestamptz NOT NULL,
    CHECK (
        (receipt_state IN ('COMPLETED', 'RETURNED') AND completed_at IS NOT NULL)
        OR (receipt_state IN ('PENDING', 'CANCELLED'))
    )
);

CREATE TABLE IF NOT EXISTS minimarket.receipt_lines (
    receipt_line_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id integer NOT NULL REFERENCES minimarket.receipts(receipt_id),
    item_id integer NOT NULL REFERENCES minimarket.catalog_items(item_id),
    sold_quantity numeric(12, 3) NOT NULL CHECK (sold_quantity > 0),
    unit_price numeric(14, 2) NOT NULL CHECK (unit_price >= 0),
    line_total numeric(14, 2) GENERATED ALWAYS AS (sold_quantity * unit_price) STORED
);

CREATE TABLE IF NOT EXISTS minimarket.refunds (
    refund_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_number text NOT NULL UNIQUE,
    receipt_id integer NOT NULL REFERENCES minimarket.receipts(receipt_id),
    refund_state text NOT NULL CHECK (
        refund_state IN ('COMPLETED', 'PENDING', 'CANCELLED')
    ),
    refunded_at timestamptz,
    created_at timestamptz NOT NULL,
    changed_at timestamptz NOT NULL,
    CHECK (
        (refund_state = 'COMPLETED' AND refunded_at IS NOT NULL)
        OR refund_state IN ('PENDING', 'CANCELLED')
    )
);

CREATE TABLE IF NOT EXISTS minimarket.refund_lines (
    refund_line_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id integer NOT NULL REFERENCES minimarket.refunds(refund_id),
    receipt_line_id integer NOT NULL REFERENCES minimarket.receipt_lines(receipt_line_id),
    returned_quantity numeric(12, 3) NOT NULL CHECK (returned_quantity > 0),
    refund_total numeric(14, 2) NOT NULL CHECK (refund_total >= 0)
);

CREATE TABLE IF NOT EXISTS private_internal.admin_notes (
